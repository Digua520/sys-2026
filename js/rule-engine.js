    selfAwareness:    { 'q7': { A: 1, B: -2, C: 2 }, 'q10': { A: -2, B: -1, C: 2 } },
    riskTolerance:    { 'q1b': { A: 2, B: 1, C: -1 }, 'q8': { A: -1, B: 0, C: 1 } },
