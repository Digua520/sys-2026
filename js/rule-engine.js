// ============================================================
// 六、主入口：生成完整路书
// ============================================================

function generateRoadmap(answers) {
  const { archetype, scores, matchQuality } = matchArchetype(answers);
  const dims = computeDimensions(answers);

  let roadmap = {
    // 基本信息
    archetypeName: archetype.name,
    matchQuality,
    dimensions: dims,

    // 四大板块
    生存战壕: archetype.战壕,
    反杀手段: archetype.反杀手段,
    情感防弹衣: archetype.情感防弹衣,
    热血定调: archetype.热血定调,

    // 元数据
    generatedAt: new Date().toISOString(),
    answerProfile: answers
  };

  // 应用个性化微调
  roadmap = applyPersonalization(roadmap, answers);

  return roadmap;
}

