// 三、匹配算法
// ============================================================

function matchArchetype(answers) {
  let bestScore = -Infinity;
  let bestMatch = null;
  const scores = [];

  for (let archetype of ARCHETYPES) {
    let score = 0;
    for (let rule of archetype.matchRules) {
      const userAnswer = answers[rule.q];
      if (userAnswer === rule.v) {
        score += rule.weight || 1;
      }
    }
    scores.push({ id: archetype.id, name: archetype.name, score });
    if (score > bestScore) {
      bestScore = score;
      bestMatch = archetype;
    }
  }

  // 如果最高分仍然过低（< 3），返回通用模板
  if (bestScore < 3) {
    return {
      archetype: generateGenericRoadmap(answers),
      scores,
      matchQuality: 'low'
    };
  }

  return {
    archetype: bestMatch,
    scores,
    matchQuality: bestScore >= 8 ? 'high' : 'medium'
  };
}

